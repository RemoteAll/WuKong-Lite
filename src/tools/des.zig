fn permute(comptime in_bits: u7, input: u64, table: []const u8) u64 {
    var out: u64 = 0;
    for (table) |pos| {
        const shift: u6 = @intCast(in_bits - @as(u7, @intCast(pos)));
        out = (out << 1) | ((input >> shift) & 1);
    }
    return out;
}

fn keySchedule(key: [8]u8) [16]u64 {
    var k: u64 = 0;
    for (key) |b| k = (k << 8) | b;
    const pc1 = permute(64, k, &PC1);
    var c: u32 = @truncate(pc1 >> 28);
    var d: u32 = @truncate(pc1 & 0x0FFFFFFF);
    var subkeys: [16]u64 = undefined;
    for (0..16) |i| {
        const n = SHIFTS[i];
        c = ((c << n) | (c >> @intCast(28 - @as(u32, n)))) & 0x0FFFFFFF;
        d = ((d << n) | (d >> @intCast(28 - @as(u32, n)))) & 0x0FFFFFFF;
        const cd = (@as(u64, c) << 28) | @as(u64, d);
        subkeys[i] = permute(56, cd, &PC2);
    }
    return subkeys;
}

fn feistel(r: u32, subkey: u64) u32 {
    const expanded = permute(32, @as(u64, r), &E) ^ subkey;
    var s_out: u32 = 0;
    for (0..8) |i| {
        const shift: u6 = @intCast(42 - 6 * i);
        const six: u6 = @intCast((expanded >> shift) & 0x3F);
        const row: usize = ((six >> 4) & 0x2) | (six & 0x1);
        const col: usize = (six >> 1) & 0xF;
        s_out = (s_out << 4) | S_BOX[i][row * 16 + col];
    }
    return @truncate(permute(32, @as(u64, s_out), &P));
}

/// 单块 DES 加密（ECB，无填充）。
pub fn encryptBlock(key: [8]u8, block: *[8]u8) void {
    var input: u64 = 0;
    for (block.*) |b| input = (input << 8) | b;

    const subkeys = keySchedule(key);
    const ip = permute(64, input, &IP);
    var l: u32 = @truncate(ip >> 32);
    var r: u32 = @truncate(ip & 0xFFFFFFFF);

    for (0..16) |i| {
        const next = l ^ feistel(r, subkeys[i]);
        l = r;
        r = next;
    }

    const pre = (@as(u64, r) << 32) | @as(u64, l);
    const out = permute(64, pre, &FP);
    for (0..8) |i| {
        const shift: u6 = @intCast(56 - 8 * i);
        block.*[i] = @truncate(out >> shift);
    }
}

test "DES：标准向量" {
    var block = [8]u8{ 0x4E, 0x6F, 0x77, 0x20, 0x69, 0x73, 0x20, 0x74 };
    encryptBlock(.{ 0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF }, &block);
    try std.testing.expectEqualSlices(u8, &.{ 0x3F, 0xA4, 0x0E, 0x8A, 0x98, 0x4D, 0x48, 0x15 }, &block);
}

test "DES：全零向量" {
    var block = [8]u8{ 0, 0, 0, 0, 0, 0, 0, 0 };
    encryptBlock(.{ 0, 0, 0, 0, 0, 0, 0, 0 }, &block);
    try std.testing.expectEqualSlices(u8, &.{ 0x8C, 0xA6, 0x4D, 0xE9, 0xC1, 0xB1, 0x23, 0xA7 }, &block);
}
